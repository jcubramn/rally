import assert from 'node:assert/strict';
import {periodKey,periodLabel,periodSessions,periodWeeks,trainingPeriod,shiftWeek} from '../lib/weeks';
import {invoiceDraft} from '../lib/invoice';
import {initial,validWorkspace,type Client} from '../lib/tennis';
assert.equal(periodKey(new Date('2026-09-22T12:00:00')),'2026-09-14');
assert.equal(periodKey(new Date('2026-09-28T12:00:00')),'2026-09-28');
assert.equal(periodLabel('2026-09-14'),'Sep 14 – Sep 27, 2026');
const hit={day:0,planId:'rally',time:'16:00',endTime:'17:00',completed:true};
const client:Client={...initial.clients[0],weeks:{'2026-09-14':{sessions:[hit]},'2026-09-21':{sessions:[{...hit,day:4,endTime:'17:30'},{...hit,day:1,completed:false}]},'2026-09-28':{sessions:[hit]}}};
const sessions=periodSessions(client,'2026-09-14',true);
assert.deepEqual(sessions.map(s=>s.day),[0,11,8]);
const invoice=invoiceDraft('Riley','2026-09-14',sessions,'hour','80','',true);
assert.equal(invoice.totalCents,20000);assert(invoice.text.includes('Fri, Sep 25'));assert(invoice.text.includes('150 minutes total'));assert(!invoice.text.includes('Tue, Sep 22'));
assert.equal(invoiceDraft('Riley','2026-09-14',sessions,'hit','50','',true).totalCents,10000);
assert.equal(invoiceDraft('Riley','2026-09-14',sessions,'flat','75','',true).totalCents,7500);
const weeks=periodWeeks(client,'2026-09-14',sessions.map(s=>s.day===0?{...s,day:9}:s));
assert.equal(weeks['2026-09-14'].sessions.length,0);assert(weeks['2026-09-21'].sessions.some(s=>s.day===2&&s.completed));assert.deepEqual(weeks['2026-09-28'],client.weeks!['2026-09-28']);assert(validWorkspace({...initial,clients:[{...client,weeks}]}));
const planned=trainingPeriod(client,'2026-09-14',[0,7,11],'rally');assert.equal(planned.sessions.length,3);assert(planned.sessions.find(s=>s.day===11)?.completed);
assert.equal(periodSessions({...client,weeks:{'2026-09-14':client.weeks!['2026-09-14']}},'2026-09-14',true).length,1);
assert.equal(shiftWeek('2026-09-14',2),'2026-09-28');
console.log('Passed two-week navigation, preserved weekly storage, cross-week moves, completed-only invoices and all three billing methods.');
